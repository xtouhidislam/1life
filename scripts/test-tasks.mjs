import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
import { PGlite } from '@electric-sql/pglite';

const source = ts.transpile(readFileSync('src/task-utils.ts', 'utf8'), { module: ts.ModuleKind.ESNext });
const { dhakaDate, shiftDate, duration, overlaps } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
assert.equal(dhakaDate(new Date('2026-10-31T17:59:59Z')), '2026-10-31');
assert.equal(dhakaDate(new Date('2026-10-31T18:00:00Z')), '2026-11-01');
assert.equal(shiftDate('2027-01-01', -1), '2026-12-31');
assert.equal(duration('23:30', '00:00'), 30);
assert.equal(duration('00:00', '05:30'), 330);
assert.equal(overlaps({ start_time: '23:00', end_time: '01:00' }, { start_time: '00:30', end_time: '02:00' }), true);
assert.equal(overlaps({ start_time: '23:00', end_time: '01:00' }, { start_time: '01:00', end_time: '02:00' }), false);

const db = new PGlite();
const a = '11111111-1111-4111-8111-111111111111', b = '22222222-2222-4222-8222-222222222222';
try {
  await db.exec(`create role anon; create role authenticated; create schema auth;
    create table auth.users(id uuid primary key);
    create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
    grant usage on schema public, auth to authenticated, anon;
    grant execute on function auth.uid() to authenticated, anon;
    insert into auth.users values ('${a}'),('${b}');`);
  for (const file of ['202610310001_foundation.sql', '202610310002_tasks.sql']) await db.exec(readFileSync(`supabase/migrations/${file}`, 'utf8'));
  const login = async id => db.exec(`reset role; set role authenticated; select set_config('request.jwt.claim.sub','${id}',false)`);
  const count = async (table, where = '') => Number((await db.query(`select count(*) as n from public.${table} ${where}`)).rows[0].n);
  await login(a);
  await db.exec('select public.prepare_task_day(); select public.prepare_task_day();');
  assert.equal(await count('task_templates'), 6, 'Defaults must not duplicate');
  const today = (await db.query("select ((now() at time zone 'Asia/Dhaka')::date)::text as date")).rows[0].date;
  const dow = new Date(`${today}T12:00:00Z`).getUTCDay();
  assert.equal(await count('task_items'), dow === 0 ? 5 : 6);
  assert.equal(await count('schedule_blocks'), 26);
  const routineTotals = (await db.query(`select routine, sum(mod(extract(epoch from end_time - start_time)::integer + 86400, 86400)/60) as minutes from public.schedule_blocks group by routine`)).rows;
  routineTotals.forEach(row => assert.equal(Number(row.minutes), 1440));
  const target = (await db.query("select id from public.task_templates where title='Read 10 pages'")).rows[0].id;
  await db.exec(`update public.task_templates set start_date = '${today}'::date - 3 where id='${target}'; select public.prepare_task_day();`);
  assert.equal(await count('task_items', `where template_id='${target}'`), 4, 'Missed days must be backfilled');
  await db.exec(`update public.task_items set completed_at=now() where template_id='${target}' and task_date='${today}'; update public.task_templates set title='Read 12 pages' where id='${target}'; select public.prepare_task_day();`);
  const snapshot = (await db.query(`select title, completed_at from public.task_items where template_id='${target}' and task_date='${today}'`)).rows[0];
  assert.equal(snapshot.title, 'Read 10 pages'); assert.ok(snapshot.completed_at);
  await db.exec(`update public.task_templates set archived_from='${today}'::date+1 where id='${target}'; select public.prepare_task_day();`);
  assert.equal(await count('task_items', `where template_id='${target}'`), 4, 'Archive must preserve history');
  await assert.rejects(() => db.exec(`delete from public.task_templates where id='${target}'`), /permission denied/);
  await assert.rejects(() => db.exec(`insert into public.task_items (user_id,task_date,title) values ('${b}','${today}','Forbidden')`), /row-level security/);
  await assert.rejects(() => db.exec(`insert into public.task_items (task_date,title,completed_at) values ('${today}'::date+1,'Future',now())`), /check constraint/);
  await db.exec(`insert into public.task_items (task_date,title) values ('${today}','Manual task')`);
  await db.exec("update public.task_items set title='Edited task', priority='high', tag='Test' where title='Manual task'");
  assert.equal(await count('task_items', "where title='Edited task' and priority='high'"), 1);
  await db.exec("delete from public.task_items where title='Edited task'");
  assert.equal(await count('task_items', "where title='Edited task'"), 0);
  await login(b);
  for (const table of ['task_items','task_templates','schedule_blocks']) assert.equal(await count(table), 0, 'B must not read A records');
  const changed = await db.query(`update public.task_items set title='Hacked' where user_id='${a}' returning id`);
  assert.equal(changed.rows.length, 0);
  const removed = await db.query(`delete from public.task_items where user_id='${a}' returning id`);
  assert.equal(removed.rows.length, 0);
  await assert.rejects(() => db.exec(`insert into public.task_items(template_id,task_date,title) values ('${target}','${today}'::date+1,'Cross-owner template')`), /foreign key/);
  await db.exec('select public.prepare_task_day()');
  assert.equal(await count('task_templates'), 6);
  await login(a);
  assert.equal(await count('task_items', `where template_id='${target}'`), 4);
  await db.exec("reset role; set role anon; select set_config('request.jwt.claim.sub','',false)");
  await assert.rejects(() => db.exec('select * from public.task_items'), /permission denied/);
  await assert.rejects(() => db.exec('select public.prepare_task_day()'), /permission denied/);
  console.log('PASS: Dhaka midnight, year rollover, overnight time/overlap; SQL migrations; idempotent defaults; backfill; history preservation; archive; task CRUD; future completion constraint; cross-owner isolation; anonymous denial.');
} finally { await db.close(); }
